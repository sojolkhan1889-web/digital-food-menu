/**
 * Media Storage & CDN Service for 3D Digital Food Menu.
 * 
 * Provides a clean abstraction for:
 * 1. Uploading optimized WebP images to static server storage (/uploads).
 * 2. Serving images with zero Supabase database egress.
 * 3. Plug-and-Play compatibility with Cloudflare CDN or Private VPS in production.
 */

// If VITE_CDN_URL is configured (e.g. 'https://cdn.myrestaurantmenu.com'), relative /uploads are prefixed with it.
const CDN_URL = (typeof import.meta !== 'undefined' && import.meta.env?.VITE_CDN_URL) || '';

/**
 * Resolves any image URL, adding CDN prefix if configured and handling placeholders.
 */
export function resolveMediaUrl(url, fallback = '/Food.gif') {
  if (!url || typeof url !== 'string' || !url.trim()) {
    return fallback;
  }
  const clean = url.trim();

  // If already absolute HTTP/HTTPS or inline Data URL
  if (clean.startsWith('http://') || clean.startsWith('https://') || clean.startsWith('data:image/')) {
    return clean;
  }

  // Prepend CDN URL if configured and path starts with /
  if (CDN_URL && clean.startsWith('/')) {
    return `${CDN_URL.replace(/\/$/, '')}${clean}`;
  }

  return clean;
}

/**
 * Uploads an optimized media file / data URL to the server storage endpoint (/api/media/upload).
 * 
 * In Development: Handled by Vite dev server middleware, saving directly to public/uploads/.
 * In Production (VPS): Handled by the VPS upload endpoint, saving to /uploads/ with CDN cache headers.
 * Fallback: If server endpoint is unreachable, safely returns the compressed WebP Data URL.
 * 
 * @param {string} dataUrl - Optimized WebP Base64 Data URL (e.g. generated by compressImage)
 * @param {object} options - { filename, folder }
 * @returns {Promise<{ success: boolean, url: string, isLocalFallback: boolean }>}
 */
export async function uploadMediaFile(dataUrl, options = {}) {
  const { filename = 'dish_photo', folder = 'foods' } = options;

  if (!dataUrl || typeof dataUrl !== 'string') {
    return { success: false, url: '', isLocalFallback: false, error: 'Empty dataUrl' };
  }

  // If the URL is already a static path (e.g. /burger_combo.jpg), return as-is
  if (dataUrl.startsWith('/') || (dataUrl.startsWith('http') && !dataUrl.startsWith('data:image/'))) {
    return { success: true, url: dataUrl, isLocalFallback: false };
  }

  try {
    const response = await fetch('/api/media/upload', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        dataUrl,
        filename,
        folder
      })
    });

    if (response.ok) {
      const result = await response.json();
      if (result && result.url) {
        console.log(`[MediaStorage] Upload successful -> ${result.url} (${result.sizeKb} KB)`);
        return {
          success: true,
          url: result.url,
          filename: result.filename,
          isLocalFallback: false
        };
      }
    }
    console.warn('[MediaStorage] Upload API returned non-OK status:', response.status);
  } catch (err) {
    console.warn('[MediaStorage] Upload API offline, using optimized inline fallback:', err.message);
  }

  // Fallback: Return the compressed Data URL directly (safe fallback if backend is offline)
  return {
    success: true,
    url: dataUrl,
    isLocalFallback: true
  };
}
